import re
from typing import List, Optional

from app.services.file_text import ExtractedContent


def build_grading_prompt(
    assignment_title: str,
    brief_md: str,
    author_name: str,
    is_group_work: bool,
    group_members: Optional[List[dict]],
    extracted: ExtractedContent,
    images_sent: Optional[int] = None,
) -> str:
    """Промпт проверки.

    Тон доброжелательный: оценку снижаем за содержание, а не за формат, а на
    ручную проверку работу отправляем только когда её реально нечем проверить.

    `images_sent` — сколько изображений реально ушло в запрос. Если их меньше, чем
    найдено в файле, модель знает об этом и не считает непереданное отсутствующим.
    """
    members_text = ""
    if is_group_work and group_members:
        members_text = "\n".join(
            f"- {m.get('first_name', '')} {m.get('last_name', '')}" for m in group_members
        )

    notes_text = "\n".join(f"- {n}" for n in extracted.notes) if extracted.notes else "нет"

    # Tika оставляет в тексте метки вида ![](embedded:image3.png): они показывают,
    # к какому пункту работы относится скриншот, и порядок картинок тот же
    inline_refs = len(re.findall(r"!\[\]\(embedded:", extracted.text or ""))
    refs_note = (
        f"\nВ тексте работы есть метки вида `embedded:image3.png` (всего {inline_refs}): каждая "
        "показывает, к какому пункту относится скриншот. Изображения приложены в том же "
        "порядке, что и эти метки.\n"
        if inline_refs
        else ""
    )

    total_images = len(extracted.images_base64)
    sent_images = total_images if images_sent is None else min(images_sent, total_images)
    if sent_images < total_images:
        images_note = (
            f"В файле найдено {total_images} изображений, в этом запросе только {sent_images} — "
            f"остальные не влезли в лимит. Считай их НЕВИДЕННЫМИ, а не отсутствующими у студента."
        )
    elif total_images:
        images_note = f"Изображений, приложенных к работе: {total_images} (все переданы тебе)."
    else:
        images_note = "Изображений в работе не найдено ни одного."

    prompt = f"""Ты — преподаватель, который проверяет учебное задание доброжелательно.
Твоя задача — найти в работе то, что засчитывать, а не повод снизить балл.
Не додумывай требования, которых нет в тексте задания. Все спорные толкования
трактуй в пользу студента.

## Задание
Название: {assignment_title}

{brief_md}

## Сданная работа
Автор (основной): {author_name}
{"Работа групповая. Участники:\n" + members_text if is_group_work else "Работа индивидуальная."}

### Текстовая часть работы
{extracted.text or "(текстовое содержимое отсутствует)"}

### Что известно об изображениях
{images_note}{refs_note}

### Примечания к файлу
{notes_text}

## Шаг 1. Можно ли вообще проверить работу
Оценивать можно, если ты видишь хотя бы часть выполнения: текст работы, результат
или хотя бы часть требуемых изображений. Тогда сразу переходи к шагу 2 — даже если
чего-то из деталей не хватает.

verdict="manual_review" ставь только в двух случаях, когда проверять буквально нечего:

- задание явно требует изображения (скриншоты, схемы, графики), а в работе нет НИ
  одного изображения и по тексту результат подтвердить нельзя;
- из файла не удалось извлечь ничего: нет и текста, и изображений (пустой файл,
  неподдерживаемый формат, ошибки в «Примечаниях к файлу»).

Не уводите работу на ручную проверку, если:
не хватает одного скриншота из нескольких, но из текста видно, что этап пройден;
изображений передано меньше, чем в файле, но видимого достаточно для оценки;
работа оформлена не по шаблону, скриншоты подписаны не так, ответ короткий или
дан своими словами.

Во всех этих случаях просто поставь оценку и, если нужно, вежливо отметь недочёт
в feedback — преподаватель увидит замечание и решит сам.

## Шаг 2. Оценка
Оцени работу по шкале от 2 до 5. Снижай балл только за содержание: невыполненные
пункты задания, фактические ошибки, не по теме.

- 5 — задание выполнено полностью
- 4 — выполнено, есть небольшие недочёты по существу
- 3 — выполнена большая часть, но заметные пробелы в содержании
- 2 — по сути не выполнено (пусто, не по теме, сдана заглушка)

Не снижай балл и не упоминай как недостаток за: оформление, объём, вёрстку,
орфографию, стиль, формат файла, отсутствие title/подписей у скриншотов,
повторяющиеся картинки, отсутствие скриншота того, что видно из текста.

Если в работе есть изображения (скриншоты, блок-схемы, диаграммы), учитывай их
содержимое при оценке.

## Формат ответа
Ответь СТРОГО в формате JSON без Markdown-разметки:
{{"verdict": "ok" | "manual_review", "grade": <2-5 или null>, "feedback": "<короткое пояснение на русском языке: что засчитано, что можно улучшить>", "missing": [<что не нашёл, пустой массив для verdict="ok">]}}

Для verdict="ok" grade обязателен и missing пуст. Для verdict="manual_review" grade=null, missing непуст.
"""
    return prompt
