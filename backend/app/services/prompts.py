from typing import List, Optional

from app.services.file_text import ExtractedContent


def build_grading_prompt(
    assignment_title: str,
    brief_md: str,
    author_name: str,
    is_group_work: bool,
    group_members: Optional[List[dict]],
    extracted: ExtractedContent,
    images_sent: Optional[int] = None,
) -> str:
    """Промпт проверки.

    `images_sent` — сколько изображений реально ушло в запрос. Если их меньше, чем
    найдено в файле, модель обязана честно сказать об этом, а не додумывать оценку
    по обрезанным материалам.
    """
    members_text = ""
    if is_group_work and group_members:
        members_text = "\n".join(
            f"- {m.get('first_name', '')} {m.get('last_name', '')}" for m in group_members
        )

    notes_text = "\n".join(f"- {n}" for n in extracted.notes) if extracted.notes else "нет"

    total_images = len(extracted.images_base64)
    sent_images = total_images if images_sent is None else min(images_sent, total_images)
    if sent_images < total_images:
        images_note = (
            f"В файле найдено {total_images} изображений, в этом запросе только {sent_images} — "
            f"остальные не влезли в лимит. Считай их НЕВИДЕННЫМИ, а не отсутствующими у студента."
        )
    elif total_images:
        images_note = f"Изображений, приложенных к работе: {total_images} (все переданы тебе)."
    else:
        images_note = "Изображений в работе не найдено ни одного."

    prompt = f"""Ты — строгий преподаватель, проверяющий учебное задание.

## Задание
Название: {assignment_title}

{brief_md}

## Сданная работа
Автор (основной): {author_name}
{"Работа групповая. Участники:\n" + members_text if is_group_work else "Работа индивидуальная."}

### Текстовая часть работы
{extracted.text or "(текстовое содержимое отсутствует)"}

### Что известно об изображениях
{images_note}

### Примечания к файлу
{notes_text}

## Шаг 1. Проверь комплектность
Сравни требования задания с тем, что фактически передано: текст и изображения выше.
Оценка тебе НЕ нужна, если обязательных материалов не хватает. Возвращай
verdict="manual_review", когда:

- в задании требуются скриншоты, блок-схемы, графики или иные изображения, а среди
  переданных изображений их нет;
- текст работы ссылается на рисунки/скриншоты («см. рисунок», «на скрине видно»),
  которых среди переданных изображений нет;
- изображений не хватает, чтобы проверить требуемое количество (например, просили
  по скриншоту на каждый этап, а прислан один);
- из файла не удалось извлечь содержимое: пустой текст, неподдерживаемый формат,
  ошибки в «Примечаниях к файлу» — то есть ты физически не видишь работу;
- часть изображений не передана из-за лимита и без них работу проверить нельзя.

В этих случаях оценку не выдумывай: ставь grade=null, перечисляй в missing, чего
именно не хватает (кратко, по пунктам), и в feedback объясняй преподавателю, что
проверить нельзя и на что посмотреть руками.

## Шаг 2. Только если комплектность в порядке — оцени
Оцени работу по шкале от 2 до 5:
- 5 — отлично, задание выполнено полностью и качественно
- 4 — хорошо, небольшие недочёты
- 3 — удовлетворительно, есть заметные проблемы
- 2 — неудовлетворительно, задание не выполнено

Если в работе есть изображения (скриншоты, блок-схемы, диаграммы), учитывай их содержимое при оценке.

## Формат ответа
Ответь СТРОГО в формате JSON без Markdown-разметки:
{{"verdict": "ok" | "manual_review", "grade": <2-5 или null>, "feedback": "<развёрнутое пояснение на русском языке>", "missing": [<что не нашёл, пустой массив для verdict="ok">]}}

Для verdict="ok" grade обязателен и missing пуст. Для verdict="manual_review" grade=null, missing непуст.
"""
    return prompt
